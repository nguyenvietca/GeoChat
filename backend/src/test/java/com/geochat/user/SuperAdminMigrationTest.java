package com.geochat.user;

import java.nio.charset.StandardCharsets;
import java.sql.DriverManager;
import org.junit.jupiter.api.Test;
import static org.assertj.core.api.Assertions.*;

class SuperAdminMigrationTest {
    @Test void migrationCreatesDisabledSeedAndNeverPromotesUsernameCollision() throws Exception {
        for (boolean collision : new boolean[]{false, true}) {
            try (var db = DriverManager.getConnection("jdbc:h2:mem:super_migration_" + collision + ";MODE=PostgreSQL;DATABASE_TO_UPPER=false")) {
                try (var sql = db.createStatement()) {
                    sql.execute("CREATE TABLE users(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username VARCHAR(255) UNIQUE NOT NULL, password_hash TEXT NOT NULL, password_login_enabled BOOLEAN NOT NULL, display_name VARCHAR(255) NOT NULL, status VARCHAR(32) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL, nearby_discoverable BOOLEAN NOT NULL)");
                    if (collision) sql.execute("INSERT INTO users(username,password_hash,password_login_enabled,display_name,status,created_at,updated_at,nearby_discoverable) VALUES ('geochat_super_admin','existing-hash',TRUE,'Existing user','ACTIVE',CURRENT_TIMESTAMP,CURRENT_TIMESTAMP,FALSE)");
                    for (String migration : new String[]{"V20__account_lifecycle.sql", "V21__super_admin_and_password_reset.sql"}) {
                        try (var input = getClass().getResourceAsStream("/db/migration/" + migration)) {
                            sql.execute(new String(input.readAllBytes(), StandardCharsets.UTF_8));
                        }
                    }
                    try (var row = sql.executeQuery("SELECT role,status,password_login_enabled,password_hash FROM users WHERE username='geochat_super_admin'")) {
                        assertThat(row.next()).isTrue();
                        assertThat(row.getString(1)).isEqualTo(collision ? "USER" : "SUPER_ADMIN");
                        assertThat(row.getString(2)).isEqualTo(collision ? "ACTIVE" : "LOCKED");
                        assertThat(row.getBoolean(3)).isEqualTo(collision);
                        assertThat(row.getString(4)).isEqualTo(collision ? "existing-hash" : "!bootstrap-required");
                        assertThat(row.next()).isFalse();
                    }
                    sql.execute("INSERT INTO password_reset_tokens(token_hash,user_id,email,auth_version,expires_at) VALUES ('hash',1,'test@example.com',0,CURRENT_TIMESTAMP)");
                    assertThatThrownBy(() -> sql.execute("INSERT INTO password_reset_tokens(token_hash,user_id,email,auth_version,expires_at) VALUES ('hash',1,'test@example.com',0,CURRENT_TIMESTAMP)")).isInstanceOf(java.sql.SQLException.class);
                }
            }
        }
    }
}
